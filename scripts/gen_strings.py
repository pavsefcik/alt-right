def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def render(mapping: dict) -> str:
    lines = [
        "/* Alt Right — generated by scripts/gen_strings.py */",
    ]
    for key, value in mapping.items():
        lines.append(f'"{escape(key)}" = "{escape(value)}";')
    return "\n".join(lines) + "\n"


def write(target: str, keys: list, language: str, mapping: dict) -> None:
    directory = ROOT / target / f"{language}.lproj"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "Localizable.strings").write_text(render(mapping), encoding="utf-8")


