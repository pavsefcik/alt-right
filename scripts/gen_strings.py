#!/usr/bin/env python3
"""Writes `en.lproj/Localizable.strings` for both targets.

The app is English only: keys *are* the English text (`L("Add Bookmark…")`), so
a missing entry degrades to readable English instead of a raw key. That means
there is nothing to translate and nothing to keep in sync by hand — this script
collects the `L("…")` literals from the sources and writes them back out, which
keeps the string table honest about what the UI actually says.

Run: python3 scripts/gen_strings.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = ("AltRight", "AltRightFinderSync")
L_CALL = re.compile(r'L\(\s*"((?:[^"\\]|\\.)*)"\s*\)')


def keys(for_target: str) -> list:
    found = []
    for path in sorted((ROOT / for_target).rglob("*.swift")):
        for match in L_CALL.finditer(path.read_text(encoding="utf-8")):
            key = match.group(1)
            if key not in found:
                found.append(key)
    return found


def render(keys: list) -> str:
    lines = ["/* Alt Right — generated by scripts/gen_strings.py */"]
    # The keys come out of Swift string literals, so they are already escaped
    # the way a .strings file wants them ("\n\n" stays a two-character escape).
    lines.extend(f'"{key}" = "{key}";' for key in keys)
    return "\n".join(lines) + "\n"


def main() -> None:
    for target in TARGETS:
        directory = ROOT / target / "en.lproj"
        directory.mkdir(parents=True, exist_ok=True)
        found = keys(target)
        (directory / "Localizable.strings").write_text(
            render(found), encoding="utf-8"
        )
        print(f"{target}: {len(found)} strings")


if __name__ == "__main__":
    main()
